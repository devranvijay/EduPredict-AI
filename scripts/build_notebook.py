def segment(module, name):
    """Exact source text of a top-level function, class or assignment in src/<module>.py."""
    text = (SRC / f"{module}.py").read_text(encoding="utf-8")
    for node in ast.parse(text).body:
        if isinstance(node, (ast.FunctionDef, ast.ClassDef)) and node.name == name:
            return ast.get_source_segment(text, node)
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id == name:
            return ast.get_source_segment(text, node)
    raise KeyError(f"{name} not found in src/{module}.py")


